#!/usr/bin/env node
/**
 * Renders the mark's SVG sources into every slot it fills (task 011, 07 §1), and writes the XML the in-app `Mark`
 * component draws. Colours come from src/ui/tokens.ts, so the icon and the splash follow the tokens.
 *
 * The committed files must be exactly what this produces: CI runs it again and fails on any difference. Until
 * task 018 replaces the SVG sources, every slot holds a plainly marked placeholder, and this reports how many remain.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import resvg from '@resvg/resvg-js';

import { colors } from '../src/ui/tokens.ts';

const MOBILE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = path.join(MOBILE_ROOT, 'assets', 'brand');
const IMAGES = path.join(MOBILE_ROOT, 'assets', 'images');
const GENERATED = path.join(MOBILE_ROOT, 'src', 'ui', 'brand', 'marks.generated.ts');
const LEVELS = ['full', 'reduced', 'silhouette', 'glyph'];

function readMark(level) {
  const source = readFileSync(path.join(SOURCES, `mark-${level}.svg`), 'utf8');
  const [, attributes, content] = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
  return {
    viewBox: attributes.match(/viewBox="([^"]+)"/)[1],
    body: content.replace(/<!--[\s\S]*?-->/g, '').replace(/>\s+</g, '><').trim(),
    placeholder: /data-placeholder="true"/.test(attributes),
  };
}

const marks = Object.fromEntries(LEVELS.map((level) => [level, readMark(level)]));
const { dark, light } = colors;

/** A square canvas with an optional ground, the mark centred on it in one flat colour. */
function render({ canvas, level = null, markSize = canvas, ink = dark.textPrimary, ground = null }) {
  const offset = (canvas - markSize) / 2;
  const mark = level === null ? null : marks[level];
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${canvas}" height="${canvas}" viewBox="0 0 ${canvas} ${canvas}" color="${ink}">`,
    ground === null ? '' : `<rect width="${canvas}" height="${canvas}" fill="${ground}"/>`,
    mark === null
      ? ''
      : `<svg x="${offset}" y="${offset}" width="${markSize}" height="${markSize}" viewBox="${mark.viewBox}">${mark.body}</svg>`,
    '</svg>',
  ].join('');
  return new resvg.Resvg(svg, { fitTo: { mode: 'original' }, font: { loadSystemFonts: false } }).render().asPng();
}

// Sizes are rendered sizes (07 §1): the launcher icon is shown about 48 dp across, so it takes silhouette + eyes.
const SLOTS = [
  // The legacy icon and the Play Store icon, kept identical to the launcher icon.
  { file: 'icon.png', level: 'silhouette', canvas: 1024, markSize: 640, ground: dark.bgAbyss },
  // The adaptive icon: a 108 dp canvas whose central 66 dp are never masked.
  { file: 'android-icon-foreground.png', level: 'silhouette', canvas: 432, markSize: 264 },
  { file: 'android-icon-background.png', canvas: 432, ground: dark.bgAbyss },
  { file: 'android-icon-monochrome.png', level: 'silhouette', canvas: 432, markSize: 264 },
  // The splash: the reduced drawing at 128 dp, rendered 4× for the densest screens, once per theme.
  { file: 'splash-icon.png', level: 'reduced', canvas: 512, ink: light.textPrimary },
  { file: 'splash-icon-dark.png', level: 'reduced', canvas: 512, ink: dark.textPrimary },
  // The glyph. Android draws a notification icon from its alpha channel alone. Wired when notifications exist.
  { file: 'notification-icon.png', level: 'glyph', canvas: 96 },
  { file: 'favicon.png', level: 'glyph', canvas: 48, ink: light.textPrimary },
];

mkdirSync(IMAGES, { recursive: true });
for (const slot of SLOTS) {
  writeFileSync(path.join(IMAGES, slot.file), render(slot));
}

const placeholders = LEVELS.filter((level) => marks[level].placeholder);
mkdirSync(path.dirname(GENERATED), { recursive: true });
writeFileSync(
  GENERATED,
  [
    '// Generated by scripts/render-brand-assets.mjs from assets/brand/*.svg. Do not edit: change the SVG, then run',
    '// `pnpm render:brand`.',
    '',
    "export type MarkLevel = 'full' | 'reduced' | 'silhouette' | 'glyph';",
    '',
    '/** Each level of the mark as SVG drawn in `currentColor` (07 §1). */',
    'export const MARKS: Readonly<Record<MarkLevel, string>> = {',
    ...LEVELS.map(
      (level) =>
        `  ${level}: '<svg xmlns="http://www.w3.org/2000/svg" viewBox="${marks[level].viewBox}">${marks[level].body}</svg>',`,
    ),
    '};',
    '',
    "/** The levels still holding task 011's placeholder. Task 018 is done when this is empty. */",
    `export const PLACEHOLDER_LEVELS: readonly MarkLevel[] = [${placeholders.map((level) => `'${level}'`).join(', ')}];`,
    '',
  ].join('\n'),
);

console.log(
  `Rendered ${SLOTS.length} assets and the in-app marks. ${placeholders.length} of ${LEVELS.length} levels still hold the placeholder (task 018).`,
);
